async function runPluginDependencyBuild(root: string, pluginConfiguration: string) {
  roots.push(root);

  await linkFrameworkPackages(root);

  await mkdir(join(root, "src"), { recursive: true });

  await writeFile(
    join(root, "app.tsx"),
    "export default function App() { return <html><head></head><body>ok</body></html>; }",
  );

  const hookLog = join(root, "plugin-hooks.txt");

  const config = [
    'import { appendFile } from "node:fs/promises";',
    'import { defineConfig } from "@hesperia/tooling";',
    "const hookLog = __HOOK_LOG__;",
    "function record(name: string, marker: string, dependsOn?: string[]) {",
    "  return {",
    "    name,",
    "    ...(dependsOn ? { dependsOn } : {}),",
    "    async analyzeProject() {",
    '      await appendFile(hookLog, marker + "\\n");',
    "      return {};",
    "    },",
    "  };",
    "}",
    "__PLUGIN_CONFIGURATION__",
  ]
    .join("\n")
    .replace("__HOOK_LOG__", JSON.stringify(hookLog))
    .replace("__PLUGIN_CONFIGURATION__", pluginConfiguration);

  await writeFile(join(root, "hesperia.config.ts"), config);

  let failure: unknown;

  try {
    await buildInProjectProcess(root, false);
  } catch (error) {
    failure = error;
  }

  const diagnostics =
    (
      failure as
        | {
            readonly diagnostics?: readonly {
              readonly code: string;
              readonly severity: string;
              readonly message: string;
            }[];
          }
        | undefined
    )?.diagnostics ?? [];

  return {
    failure,
    diagnostics,
    hooks: existsSync(hookLog) ? await readFile(hookLog, "utf8") : "",
  };
}

function expectPluginDependencyError(
  diagnostics: readonly {
    readonly code: string;
    readonly severity: string;
    readonly message: string;
  }[],
  message: string,
): void {
  expect(diagnostics).toContainEqual(
    expect.objectContaining({
      code: "HES-PLUGIN",
      severity: "error",
      message: expect.stringContaining(message),
    }),
  );
}

