test("a configured analysis hook is cancelled with its project-worker operation", async () => {
  const root = await mkdtemp(join(tmpdir(), "hesperia-analyze-project-cancel-"));

  roots.push(root);

  await linkFrameworkPackages(root);

  await mkdir(join(root, "src"), { recursive: true });

  const started = join(root, "hook-started.txt");

  await writeFile(
    join(root, "app.tsx"),
    "export default function App() { return <html><head></head><body>ok</body></html>; }",
  );

  await writeFile(
    join(root, "hesperia.config.ts"),
    `import { writeFile } from "node:fs/promises"; import { defineConfig } from "@hesperia/tooling"; export default defineConfig({ plugins: [{ name: "slow", async analyzeProject() { await writeFile(${JSON.stringify(started)}, "yes"); await new Promise(() => {}); return {}; } }] });`,
  );

  const controller = new AbortController();

  const pending = buildInProjectProcess(root, false, controller.signal);

  const deadline = Date.now() + 10_000;

  while (!existsSync(started) && Date.now() < deadline) await Bun.sleep(20);

  expect(existsSync(started)).toBe(true);

  controller.abort();

  await expect(pending).rejects.toMatchObject({ name: "AbortError" });
});
