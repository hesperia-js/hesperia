async function insertGeneratedCssLine(): Promise<Plugin> {
  const postcssModule = await import(
    pathToFileURL(Bun.resolveSync("postcss", join(import.meta.dir, "../../packages/postcss/src")))
      .href
  );

  const postcssParser = postcssModule.default as {
    comment(options: { readonly text: string }): unknown;
  };

  return postcss({
    plugins: [
      {
        postcssPlugin: "insert-unmapped-generated-css-line",

        Once(css: PrefixPostcssRoot) {
          css.prepend(postcssParser.comment({ text: "generated by the first stage" }));
        },
      } as unknown as WarningPostcssPlugin,
    ],
  });
}

function warnPostcssNode(nodeType: string, message: string) {
  return postcss({
    plugins: [
      {
        postcssPlugin: `warn-on-${nodeType}`,

        Once(css: WarningPostcssRoot, context: { readonly result: unknown }) {
          const node = css.nodes?.find((item) => item.type === nodeType);

          if (node) css.warn(context.result, message, { node });
        },
      } as unknown as WarningPostcssPlugin,
    ],
  });
}

