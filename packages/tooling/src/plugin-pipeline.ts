/** One plugin source after ordered transforms, retaining its authored text and map. */
export interface TransformedPluginSource {
  /** Absolute filename. */
  readonly filename: string;
  /** Original authored text. */
  readonly authored: string;
  /** Text supplied to compiler checking and emission. */
  readonly current: string;
  /** Map from transformed text to authored text. */
  readonly map?: PluginSourceMap;
}

/** One import-site-specific checker and browser module generated by an import handler. */
